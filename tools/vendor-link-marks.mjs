// Spark carries Keeper's and Prism's own mark sheets as a module, so her hooks draw them without reading files.
//   node tools/vendor-link-marks.mjs     reads plugins/cyclops-spark/link-mark/{keeper,prism}.json (vendored copies)
//                                         writes plugins/cyclops-spark/hooks/link-marks.js
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
const dir = new URL('../plugins/cyclops-spark/link-mark/', import.meta.url)
let out = '// Generated by tools/vendor-link-marks.mjs from the vendored sheets in link-mark/. Do not edit: re-run it.\n' +
  '// Each is that presence\'s own look, exported by her own renderer (see link-mark/SOURCE.md).\n'
for (const p of ['keeper', 'prism']) {
  const text = readFileSync(new URL(p + '.json', dir), 'utf8').trim()
  JSON.parse(text)
  out += `// ${p}.json sha256 ${createHash('sha256').update(text + '\n').digest('hex')}\n`
  out += `export const ${p.toUpperCase()} = ${JSON.stringify(text)}\n`
}
writeFileSync(new URL('../plugins/cyclops-spark/hooks/link-marks.js', import.meta.url), out)
console.log('plugins/cyclops-spark/hooks/link-marks.js')
